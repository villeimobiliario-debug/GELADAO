CREATE OR REPLACE FUNCTION public.adjust_stock(p_product_id uuid, p_delta numeric)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare v_id uuid:=auth.uid();
begin
 if not private.is_admin() then raise exception 'Acesso negado' using errcode='42501'; end if;
 if p_delta=0 or abs(p_delta)>100000 then raise exception 'Quantidade inválida'; end if;
 update public.products set stock_qty=stock_qty+p_delta where id=p_product_id and track_stock=true and stock_qty+p_delta>=0;
 if not found then raise exception 'Produto inválido ou estoque insuficiente'; end if;
 insert into public.stock_movements(product_id,qty_change,reason,actor) values(p_product_id,p_delta,'ajuste',v_id);
end$function$


CREATE OR REPLACE FUNCTION public.advance_delivery(p_order_id uuid, p_expected_version integer)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare v public.orders%rowtype; v_actor uuid:=auth.uid();
begin
 if not private.is_staff() then raise exception 'Acesso negado' using errcode='42501'; end if;
 select * into v from public.orders where id=p_order_id for update;
 if not found or v.channel<>'delivery' or v.status='cancelled' then raise exception 'Pedido delivery inválido'; end if;
 if p_expected_version<>v.version then raise exception 'Pedido foi alterado. Atualize a página'; end if;
 if v.stage='pedidos' then
   update public.orders set delivered_at=now(),stage=case when payment_status='paid' then 'entregues' else 'aguardando_pagamento' end,
   version=version+1,updated_by=v_actor,updated_at=now() where id=p_order_id;
 elsif v.stage='aguardando_pagamento' then
   if v.payment_method='nao_informado' then raise exception 'Edite o pedido e informe a forma de pagamento antes de confirmar'; end if;
   update public.orders set payment_status='paid',paid_at=now(),stage='entregues',
     version=version+1,updated_by=v_actor,updated_at=now() where id=p_order_id;
 else
   raise exception 'Pedido já está concluído';
 end if;
 insert into public.order_events(order_id,event_type,before_data,after_data,actor)
 values(p_order_id,'avanco',to_jsonb(v),(select to_jsonb(o) from public.orders o where o.id=p_order_id),v_actor);
end$function$


CREATE OR REPLACE FUNCTION public.cancel_order(p_order_id uuid, p_expected_version integer)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare v public.orders%rowtype; v_actor uuid:=auth.uid(); item record;
begin
 if not private.is_admin() then raise exception 'Somente administrador pode cancelar pedidos' using errcode='42501'; end if;
 select * into v from public.orders where id=p_order_id for update;
 if not found or v.status='cancelled' then raise exception 'Pedido inexistente ou cancelado'; end if;
 if p_expected_version<>v.version then raise exception 'Pedido foi alterado. Atualize a página'; end if;
 for item in select i.product_id,i.quantity from public.order_items i join public.products p on p.id=i.product_id
    where i.order_id=p_order_id and p.track_stock order by i.product_id loop
   update public.products set stock_qty=stock_qty+item.quantity where id=item.product_id;
   insert into public.stock_movements(product_id,order_id,qty_change,reason,actor)
     values(item.product_id,p_order_id,item.quantity,'cancelamento',v_actor);
 end loop;
 update public.orders set status='cancelled',version=version+1,updated_at=now(),updated_by=v_actor where id=p_order_id;
 insert into public.order_events(order_id,event_type,before_data,after_data,actor)
 values(p_order_id,'cancelada',to_jsonb(v),(select to_jsonb(o) from public.orders o where o.id=p_order_id),v_actor);
end$function$


CREATE OR REPLACE FUNCTION public.save_order(p_data jsonb, p_order_id uuid DEFAULT NULL::uuid, p_expected_version integer DEFAULT NULL::integer)
 RETURNS uuid
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  v_actor uuid := auth.uid();
  v_order public.orders%rowtype;
  v_id uuid;
  v_channel text;
  v_method text;
  v_paid boolean;
  v_customer uuid;
  v_name text;
  v_phone text;
  v_fee numeric(12,2);
  v_discount numeric(12,2);
  v_subtotal numeric(12,2) := 0;
  v_cost numeric(12,2) := 0;
  v_line jsonb;
  v_product public.products%rowtype;
  v_qty numeric(12,3);
  v_unit_price numeric(12,2);
  v_line_total numeric(12,2);
  v_seen uuid[] := array[]::uuid[];
  v_new_products uuid[] := array[]::uuid[];
  v_product_id uuid;
  v_was_existing boolean := p_order_id is not null;
  v_previous jsonb;
  v_paid_at timestamptz;
  v_delivered_at timestamptz;
  v_stage text;
  v_request uuid;
begin
  if v_actor is null or not private.is_staff() then raise exception 'Acesso não autorizado' using errcode='42501'; end if;
  if jsonb_typeof(p_data) <> 'object' or jsonb_typeof(p_data->'items') <> 'array'
    or jsonb_array_length(p_data->'items') not between 1 and 80 then
    raise exception 'Pedido exige entre 1 e 80 itens'; end if;
  v_channel := p_data->>'channel';
  v_method := coalesce(nullif(p_data->>'payment_method',''), 'nao_informado');
  if v_channel not in ('balcao','delivery') then raise exception 'Canal inválido'; end if;
  if v_method not in ('dinheiro','pix','cartao','misto','nao_informado') then raise exception 'Forma de pagamento inválida'; end if;
  v_paid := coalesce((p_data->>'paid')::boolean,false);
  if v_paid and v_method='nao_informado' then raise exception 'Informe a forma de pagamento'; end if;
  v_fee := coalesce((p_data->>'delivery_fee')::numeric,0);
  v_discount := coalesce((p_data->>'discount')::numeric,0);
  if v_fee<0 or v_fee>99999 or v_discount<0 or v_discount>99999 then raise exception 'Valores inválidos'; end if;
  if v_channel='balcao' and v_fee>0 then raise exception 'Taxa de entrega apenas no delivery'; end if;
  v_customer := nullif(p_data->>'customer_id','')::uuid;
  if v_customer is not null and not exists(select 1 from public.customers where id=v_customer and active) then
    raise exception 'Cliente inválido'; end if;
  v_name := nullif(left(trim(coalesce(p_data->>'customer_name','')),160),'');
  v_phone := nullif(left(trim(coalesce(p_data->>'customer_phone','')),60),'');
  v_request := nullif(p_data->>'request_id','')::uuid;
  if p_order_id is null and v_request is not null then
    select id into v_id from public.orders where request_id=v_request;
    if found then return v_id; end if;
  end if;
  if v_was_existing then
    select * into v_order from public.orders where id=p_order_id for update;
    if not found then raise exception 'Pedido não encontrado'; end if;
    if v_order.status='cancelled' then raise exception 'Pedido cancelado não pode ser editado'; end if;
    if p_expected_version is null or p_expected_version<>v_order.version then
      raise exception 'Pedido foi alterado em outra sessão. Atualize a página'; end if;
    if v_channel<>v_order.channel then raise exception 'Canal não pode ser alterado'; end if;
    v_previous := to_jsonb(v_order);
    v_id := p_order_id;
    v_delivered_at := v_order.delivered_at;
    v_paid_at := v_order.paid_at;
  else
    v_delivered_at := case when v_channel='balcao' then now() else null end;
    v_paid_at := null;
  end if;

  -- Lock all affected products in stable order to keep stock consistent.
  select array_agg(distinct (item->>'product_id')::uuid)
  into v_new_products from jsonb_array_elements(p_data->'items') as item;
  if v_new_products is null or array_length(v_new_products,1)<>jsonb_array_length(p_data->'items') then
    raise exception 'Não repita produtos no mesmo pedido'; end if;
  perform 1 from public.products p
   where p.id=any(v_new_products) or (v_was_existing and p.id in
   (select i.product_id from public.order_items i where i.order_id=p_order_id))
   order by p.id for update;
  if v_was_existing then
    update public.products p set stock_qty=p.stock_qty+i.quantity
      from public.order_items i where i.order_id=v_id and i.product_id=p.id and p.track_stock;
    delete from public.order_items where order_id=v_id;
  end if;

  if not v_was_existing then
    insert into public.orders(channel,stage,status,customer_id,customer_name,customer_phone,street,neighborhood,house_number,complement,note,payment_method,payment_status,delivery_fee,discount,created_by,updated_by,request_id)
    values(v_channel,case when v_channel='balcao' then 'entregues' else 'pedidos' end,'active',v_customer,v_name,v_phone,
      nullif(left(trim(coalesce(p_data->>'street','')),180),''),
      nullif(left(trim(coalesce(p_data->>'neighborhood','')),100),''),
      nullif(left(trim(coalesce(p_data->>'house_number','')),30),''),
      nullif(left(trim(coalesce(p_data->>'complement','')),180),''),
      nullif(left(trim(coalesce(p_data->>'note','')),1000),''),
      v_method,case when v_paid then 'paid' else 'pending' end,v_fee,v_discount,v_actor,v_actor,v_request)
    returning id into v_id;
  end if;

  for v_line in select value from jsonb_array_elements(p_data->'items') loop
    v_product_id := (v_line->>'product_id')::uuid;
    select * into v_product from public.products where id=v_product_id;
    if not found or not v_product.active then raise exception 'Produto indisponível'; end if;
    v_qty := (v_line->>'quantity')::numeric;
    if v_qty<=0 or v_qty>100000 then raise exception 'Quantidade inválida'; end if;
    v_unit_price := v_product.sale_price;
    if v_line ? 'unit_price' and nullif(v_line->>'unit_price','') is not null then
      if not private.is_admin() and (v_line->>'unit_price')::numeric<>v_unit_price then
        raise exception 'Somente administrador pode alterar preço de produto';
      end if;
      v_unit_price := (v_line->>'unit_price')::numeric;
    end if;
    if v_unit_price<0 or v_unit_price>999999 then raise exception 'Preço inválido'; end if;
    v_line_total := round(v_unit_price*v_qty,2);
    if v_product.track_stock then
      update public.products set stock_qty=stock_qty-v_qty
        where id=v_product_id and stock_qty>=v_qty;
      if not found then raise exception 'Estoque insuficiente para %', v_product.name; end if;
      insert into public.stock_movements(product_id,order_id,qty_change,reason,actor)
        values(v_product_id,v_id,-v_qty,case when v_was_existing then 'edicao' else 'venda' end,v_actor);
    end if;
    insert into public.order_items(order_id,product_id,product_name,unit,quantity,unit_price,unit_cost,line_total,line_cost)
      values(v_id,v_product_id,v_product.name,v_product.unit,v_qty,v_unit_price,v_product.purchase_price,v_line_total,round(v_product.purchase_price*v_qty,2));
    v_subtotal := v_subtotal+v_line_total;
    v_cost := v_cost+round(v_product.purchase_price*v_qty,2);
  end loop;
  if v_discount>v_subtotal+v_fee then raise exception 'Desconto superior ao total'; end if;
  if v_paid then v_paid_at:=coalesce(v_paid_at,now()); else v_paid_at:=null; end if;
  v_stage := case when v_channel='balcao' or v_delivered_at is not null then
    case when v_paid then 'entregues' else 'aguardando_pagamento' end
    else 'pedidos' end;
  update public.orders set
    customer_id=v_customer,customer_name=v_name,customer_phone=v_phone,
    street=nullif(left(trim(coalesce(p_data->>'street','')),180),''),
    neighborhood=nullif(left(trim(coalesce(p_data->>'neighborhood','')),100),''),
    house_number=nullif(left(trim(coalesce(p_data->>'house_number','')),30),''),
    complement=nullif(left(trim(coalesce(p_data->>'complement','')),180),''),
    note=nullif(left(trim(coalesce(p_data->>'note','')),1000),''),
    payment_method=v_method,payment_status=case when v_paid then 'paid' else 'pending' end,
    subtotal=v_subtotal,delivery_fee=v_fee,discount=v_discount,total=v_subtotal+v_fee-v_discount,
    cost_total=v_cost,paid_at=v_paid_at,delivered_at=v_delivered_at,stage=v_stage,
    updated_at=now(),updated_by=v_actor,version=case when v_was_existing then version+1 else version end
    where id=v_id;
  insert into public.order_events(order_id,event_type,before_data,after_data,actor)
    values(v_id,case when v_was_existing then 'editada' else 'criada' end,v_previous,
      (select to_jsonb(o) from public.orders o where id=v_id),v_actor);
  return v_id;
end$function$


