CREATE OR REPLACE FUNCTION private.audit_restored_order_item()
 RETURNS trigger
 LANGUAGE plpgsql
 SET search_path TO ''
AS $function$
begin
 if exists(select 1 from public.products where id=old.product_id and track_stock) then
  insert into public.stock_movements(product_id,order_id,qty_change,reason,actor)
  values(old.product_id,old.order_id,old.quantity,'edicao',auth.uid());
 end if;
 return old;
end$function$


